#!/usr/bin/env python3
"""Generate the e2e test selectors from the OpenAPI spec.

The Playwright e2e specs (e2e/*.e2e.spec.cjs) hit the Go API through the proxy
and previously hardcoded `/v1/...` strings. When a route is renamed the spec
fails at runtime with no compile-time signal. This generator reads
apps/api/swag/openapi3.json and emits a single selectors module the specs import,
so a route change surfaces as a codegen diff (enforced by the pre-commit + CI
drift gates) instead of a silent 404.

Operation names mirror orval's generated function names (method + PascalCase
path segments, e.g. `POST /device/inbox/{imei}/ack` -> `postDeviceInboxImeiAck`),
so the selectors line up with `@vyzorix/api-client`.

Output: e2e/selectors/vyzorix-selectors.cjs (CommonJS — the specs `require` it).
"""
import json
import os
import re
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SPEC = os.environ.get("SPEC", os.path.join(REPO_ROOT, "apps/api/swag/openapi3.json"))
OUT = os.environ.get("OUT", os.path.join(REPO_ROOT, "e2e/selectors/vyzorix-selectors.cjs"))

API_PREFIX = "/v1"
HTTP_METHODS = {"get", "post", "put", "patch", "delete"}


def pascal(segment):
    seg = re.sub(r"[^A-Za-z0-9]+", "_", segment)
    return "".join(w[:1].upper() + w[1:] for w in seg.split("_") if w)


def op_name(method, path):
    """Mirror orval's operation naming: method + PascalCase segments."""
    name = method.lower()
    for part in path.strip("/").split("/"):
        if not part:
            continue
        if part.startswith("{") and part.endswith("}"):
            part = part[1:-1]
        name += pascal(part)
    return name


def main():
    with open(SPEC) as f:
        spec = json.load(f)

    ops = []
    for path, methods in spec.get("paths", {}).items():
        for method in methods:
            if method.lower() not in HTTP_METHODS:
                continue
            ops.append((op_name(method, path), method.upper(), path))
    ops.sort(key=lambda o: (o[0], o[1]))

    # Deterministic output: one entry per operation.
    lines = []
    lines.append("// Code generated by tooling/codegen/build_selectors.py from")
    lines.append("// apps/api/swag/openapi3.json. DO NOT EDIT MANUALLY.")
    lines.append("//")
    lines.append("// API path selectors for the Playwright e2e specs, so route changes")
    lines.append("// surface as a codegen diff instead of a silent 404.")
    lines.append("'use strict';")
    lines.append("")
    lines.append(f"const API_PREFIX = {API_PREFIX!r};")
    lines.append("")
    lines.append("/** Fill a spec path template ({param}) with values; throws if missing. */")
    lines.append("function fill(path, params) {")
    lines.append("  return API_PREFIX + path.replace(/\\{(\\w+)\\}/g, (_, key) => {")
    lines.append("    const value = params && params[key];")
    lines.append("    if (value === undefined || value === null) {")
    lines.append("      throw new Error(`vyzorixSelectors: missing path param \"${key}\" for ${path}`);")
    lines.append("    }")
    lines.append("    return encodeURIComponent(String(value));")
    lines.append("  });")
    lines.append("}")
    lines.append("")
    lines.append("const api = {")
    for name, method, path in ops:
        lines.append(f"  {name}: (params) => fill({path!r}, params),")
    lines.append("};")
    lines.append("")
    lines.append("// Flat enumeration for drift checks / iteration.")
    lines.append("const byOperation = {")
    for name, method, path in ops:
        lines.append(f"  {name}: {{ method: {method!r}, path: {path!r} }},")
    lines.append("};")
    lines.append("")
    lines.append("const all = Object.values(byOperation).map((o) => o.path);")
    lines.append("")
    lines.append("const vyzorixSelectors = { prefix: API_PREFIX, api, byOperation, all };")
    lines.append("")
    lines.append("module.exports = { vyzorixSelectors, fill };")
    lines.append("")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(lines))

    print(f"selectors: {len(ops)} operations -> {os.path.relpath(OUT, REPO_ROOT)}")


if __name__ == "__main__":
    main()
