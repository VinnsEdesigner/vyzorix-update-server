func TestParseUUIDv7_InvalidLength(t *testing.T) {
	testCases := []struct {
		name  string
		uuid  string
		wantErr bool
	}{
		{"empty", "", true},
		{"too short", "12345678-1234-7xxx-xxxx-123456789012", true},
		{"too long", "12345678-1234-7xxx-xxxx-12345678901234", true},
		{"no hyphens", "1234567812347xxx8xxx123456789012", true},
	}

	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			err := ParseUUIDv7(tc.uuid)
			if tc.wantErr && err == nil {
				t.Error("ParseUUIDv7() expected error, got nil")
			}
			if !tc.wantErr && err != nil {
				t.Errorf("ParseUUIDv7() unexpected error: %v", err)
			}
		})
	}
}

