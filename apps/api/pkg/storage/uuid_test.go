func TestUUIDv7ToTime(t *testing.T) {
	// Generate a UUID and verify the time extraction is reasonable
	uuid := NewUUIDv7()

	extractedTime, err := UUIDv7ToTime(uuid)
	if err != nil {
		t.Fatalf("UUIDv7ToTime(%s) failed: %v", uuid, err)
	}

	// Verify the extracted time is recent (within the last year from Go's perspective)
	// Using a very wide range since we just want to verify the function works
	oneYearAgo := time.Now().AddDate(-1, 0, 0)
	oneYearAhead := time.Now().AddDate(1, 0, 0)
	if extractedTime.Before(oneYearAgo) || extractedTime.After(oneYearAhead) {
		t.Errorf("UUIDv7ToTime() = %v, want time between %v and %v", extractedTime, oneYearAgo, oneYearAhead)
	}
}

func TestUUIDv7ToTime_RoundTrip(t *testing.T) {
	// Test that extracting time from a UUID gives consistent results
	uuid := NewUUIDv7()
	time1, err := UUIDv7ToTime(uuid)
	if err != nil {
		t.Fatalf("UUIDv7ToTime(%s) failed: %v", uuid, err)
	}

	time2, err := UUIDv7ToTime(uuid)
	if err != nil {
		t.Fatalf("UUIDv7ToTime(%s) second call failed: %v", uuid, err)
	}

	if !time1.Equal(time2) {
		t.Errorf("Round-trip time not deterministic: %v != %v", time1, time2)
	}
}

