func TestNewUUIDv7(t *testing.T) {
	// Test basic generation
	uuid := NewUUIDv7()
	if len(uuid) != 36 {
		t.Errorf("UUID length = %d, want 36", len(uuid))
	}

	// Check format: xxxxxxxx-xxxx-7xxx-yxxx-xxxxxxxxxxxx
	parts := strings.Split(uuid, "-")
	if len(parts) != 5 {
		t.Fatalf("UUID has %d parts, want 5", len(parts))
	}
	if len(parts[0]) != 8 || len(parts[1]) != 4 || len(parts[2]) != 4 || len(parts[3]) != 4 || len(parts[4]) != 12 {
		t.Errorf("UUID part lengths incorrect: %v", parts)
	}

	// Check version nibble in 3rd group (index 14 in full string)
	// 3rd group is parts[2], first char must be '7'
	if parts[2][0] != '7' {
		t.Errorf("UUID version nibble = %c, want '7'", parts[2][0])
	}

	// Check variant nibble in 4th group (index 19 in full string)
	// 4th group is parts[3], first 2 bits must be '8', '9', 'a', or 'b'
	variantChar := rune(parts[3][0])
	variantChars := []rune{'8', '9', 'a', 'b', 'c', 'd', 'e'}
	isValidVariant := false
	for _, vc := range variantChars {
		if variantChar == vc {
			isValidVariant = true
			break
		}
	}
	if !isValidVariant {
		t.Errorf("UUID variant nibble = %c, want 8-9 or a-e", variantChar)
	}

	// Should be parseable
	if err := ParseUUIDv7(uuid); err != nil {
		t.Errorf("NewUUIDv7() produced unparseable UUID: %v", err)
	}
}

func TestNewUUIDv7_Uniqueness(t *testing.T) {
	// Generate multiple UUIDs and ensure uniqueness
	uuids := make(map[string]bool)
	for i := 0; i < 1000; i++ {
		uuid := NewUUIDv7()
		if uuids[uuid] {
			t.Errorf("Duplicate UUID generated: %s", uuid)
		}
		uuids[uuid] = true
	}
}

func TestNewUUIDv7_TimeOrder(t *testing.T) {
	// Generate 1000 UUIDs and verify they're all in time order
	// Since we're generating them sequentially without sleep, each should have a higher/equal timestamp
	// (or same timestamp with higher counter)
	var lastTime time.Time
	for i := 0; i < 1000; i++ {
		uuid := NewUUIDv7()
		currentTime, err := UUIDv7ToTime(uuid)
		if err != nil {
			t.Fatalf("UUIDv7ToTime(%s) failed: %v", uuid, err)
		}
		if i > 0 && currentTime.Before(lastTime) {
			t.Errorf("UUID time order incorrect at iteration %d: %v should be after %v", i, currentTime, lastTime)
		}
		lastTime = currentTime
	}
}

func TestNewUUIDv7_MonotonicWithinMillisecond(t *testing.T) {
	// Within the same millisecond, UUIDs should be monotonically increasing
	// Generate many UUIDs in quick succession
	var uuids []string
	for i := 0; i < 100; i++ {
		uuid := NewUUIDv7()
		uuids = append(uuids, uuid)
	}

	// All UUIDs should be parseable
	for _, uuid := range uuids {
		if err := ParseUUIDv7(uuid); err != nil {
			t.Errorf("UUID %s failed to parse: %v", uuid, err)
		}
	}

	// All UUIDs should be unique
	seen := make(map[string]bool)
	for _, uuid := range uuids {
		if seen[uuid] {
			t.Errorf("Duplicate UUID in sequence: %s", uuid)
		}
		seen[uuid] = true
	}
}

