func TestUUIDv7ToTime_ExtractsCorrectTimestamp(t *testing.T) {
	// Known UUIDv7 with known timestamp
	// The timestamp bits are in positions 0-47 (first 12 hex chars excluding hyphens)
	// For the UUID format xxxxxxxx-xxxx-7xxx-yxxx-xxxxxxxxxxxx
	// The timestamp is encoded across the first 3 groups

	// We can verify by creating a UUID and checking that the time extraction is consistent
	uuid := NewUUIDv7()
	time1, err := UUIDv7ToTime(uuid)
	if err != nil {
		t.Fatalf("UUIDv7ToTime() failed: %v", err)
	}

	// Extract time again - should be same
	time2, err := UUIDv7ToTime(uuid)
	if err != nil {
		t.Fatalf("UUIDv7ToTime() second call failed: %v", err)
	}

	if !time1.Equal(time2) {
		t.Errorf("UUIDv7ToTime() not deterministic: %v != %v", time1, time2)
	}
}

